"""
Tilings, built natively (no JS involved).

Every world is a tiling of a constant-curvature surface (sphere / plane / hyperbolic plane) by regular polygons,
generated by placing polygons with 3x3 isometry matrices and identifying rooms that land on the same spot.
Wrapped worlds are the flat plane quotiented by a group of isometries (translations, glide reflections).
`build_specs()` flattens all of it into constant tables that the GPU dungeon generator (gen.py) samples from.

Poses are 3x3 matrices acting on points (x, y, 1) of the model surface with curvature kappa = +1 / 0 / -1.
"""
import os, json, numpy as np

TAU = 2*np.pi
_D = os.path.join(os.path.dirname(__file__), 'data')

def ck(k, d): return np.cos(d) if k > 0 else np.cosh(d) if k < 0 else 1.
def sk(k, d): return np.sin(d) if k > 0 else np.sinh(d) if k < 0 else d
def rot3(t): return np.array([[np.cos(t), -np.sin(t), 0], [np.sin(t), np.cos(t), 0], [0, 0, 1.]])
def trans3(k, d): return np.array([[ck(k, d), 0, sk(k, d)], [0, 1, 0], [-k*sk(k, d), 0, ck(k, d)]])
def aSide(n, k): return np.pi/2 - TAU*k/n          # math angle of side k of an n-gon (side 0 up, clockwise)

def spec_geom(vc):
    """geometry of a vertex recipe, e.g. [4,6,12]: curvature sign, side length, in/circum radius"""
    F = sum(.5-1/n for n in vc); kappa = 0 if abs(F-1) < 1e-9 else (-1 if F > 1 else 1)
    def ang(n, s):
        if kappa < 0: return 2*np.arcsin(np.cos(np.pi/n)/np.cosh(s/2))
        return 2*np.arcsin(min(1., np.cos(np.pi/n)/np.cos(s/2)))
    s = 1.
    if kappa != 0:
        lo, hi = 1e-6, (30. if kappa < 0 else 2*min(np.pi/n for n in vc)*(1-1e-9))
        for _ in range(200):
            mid = (lo+hi)/2; f = sum(ang(n, mid) for n in vc)-TAU
            if (f > 0) if kappa < 0 else (f < 0): lo = mid
            else: hi = mid
        s = (lo+hi)/2
    rho, Rc = {}, {}
    for n in set(vc):
        if kappa == 0: rho[n] = s/(2*np.tan(np.pi/n)); Rc[n] = s/(2*np.sin(np.pi/n))
        else:
            a = ang(n, s); ca = np.cos(a/2)/np.sin(np.pi/n); cr = np.cos(a/2)/np.sin(a/2)/np.tan(np.pi/n)
            rho[n] = np.arccosh(ca) if kappa < 0 else np.arccos(ca); Rc[n] = np.arccosh(cr) if kappa < 0 else np.arccos(cr)
    return dict(kappa=kappa, s=s, rho=rho, Rc=Rc)

def holonomy(vc): return sum(180-360/n for n in vc)-360     # turning picked up going once round a corner (degrees)

# ---- tiling specs: vertex recipe + which polygon sits across each side
def reg(p, q): return dict(vc=[p]*q, pat={p: [p]*p})
def bip(a, b, k): return dict(vc=[b if i % 2 else a for i in range(k)], pat={a: [b]*a, b: [a]*b})
def abb(a, b): return dict(vc=[a, b, b], pat={a: [b]*a, b: [b if i % 2 else a for i in range(b)]})
def abc(a, b, c): return dict(vc=[a, b, c], pat={a: [c if i % 2 else b for i in range(a)], b: [c if i % 2 else a for i in range(b)], c: [b if i % 2 else a for i in range(c)]})
def rhomb(): return dict(vc=[3, 4, 6, 4], pat={3: [4, 4, 4], 4: [3, 6, 3, 6], 6: [4]*6})
SPECDEFS = dict(
    flat=[reg(4, 4), reg(4, 4), reg(4, 4), reg(3, 6), reg(6, 3), abb(4, 8), abb(3, 12), abc(4, 6, 12), rhomb(), bip(3, 6, 4)],
    hyper=[reg(4, 5), reg(4, 6), reg(4, 7), reg(3, 7), reg(3, 8), reg(5, 4), reg(5, 5), reg(6, 4), reg(7, 3), reg(8, 3),
           abc(4, 8, 10), abc(4, 10, 12), abc(6, 8, 10), abb(4, 12), abb(5, 10), bip(3, 7, 4), bip(4, 5, 4), bip(4, 6, 4), bip(3, 8, 4)],
    sphere=[reg(3, 5), reg(5, 3), abb(4, 6), abb(3, 8), abc(4, 6, 8), abb(5, 6), abb(3, 10), bip(3, 4, 4), bip(3, 5, 4)])

def _make(d, name, group=None, sub=False):
    return dict(vc=d['vc'], pat=d['pat'], n0=d['vc'][0], name=name, gm=spec_geom(d['vc']), group=group, sub=sub)

def grid_group(W, H, wx, wy):
    g1 = None if wx == 'none' else np.array([[1, 0, W], [0, -1, H-1], [0, 0, 1.]]) if wx == 'flip' else np.array([[1, 0, W], [0, 1, 0], [0, 0, 1.]])
    g2 = None if wy == 'none' else np.array([[-1, 0, W-1], [0, 1, H], [0, 0, 1.]]) if wy == 'flip' else np.array([[1, 0, 0], [0, 1, H], [0, 0, 1.]])
    return dict(W=W, H=H, gens=[g1, g2], inv=[None if g is None else np.linalg.inv(g) for g in (g1, g2)])

def grid_spec(W, H, wx, wy):
    return _make(reg(4, 4), f'grid:{W}x{H}:{wx}:{wy}', grid_group(W, H, wx, wy), True)

def canon(spec, T):
    """bring a pose back into the fundamental domain; None if it falls off a non-wrapping edge"""
    G = spec['group']
    if not G: return T, False
    M, seam = T, False
    for _ in range(60):
        moved = False
        for a in range(2):
            if G['gens'][a] is None: continue
            c = M @ np.array([0, 0, 1.]); hi = (G['H'] if a else G['W'])-.5
            if c[a] < -.5: M = G['gens'][a] @ M; moved = seam = True
            elif c[a] > hi: M = G['inv'][a] @ M; moved = seam = True
        if not moved: break
    c = M @ np.array([0, 0, 1.])
    if c[0] < -.5 or c[0] > G['W']-.5 or c[1] < -.5 or c[1] > G['H']-.5: return None
    return M, seam

def _place_across(spec, A, k):
    """where does side k of room A lead? pure geometry: slide across the side, then reduce into the domain"""
    gm = spec['gm']; nB = spec['pat'][A['n']][k]; j0 = spec['pat'][nB].index(A['n'])
    raw = A['T'] @ rot3(aSide(A['n'], k)) @ trans3(gm['kappa'], gm['rho'][A['n']]+gm['rho'][nB]) @ rot3(np.pi-aSide(nB, j0))
    return nB, j0, canon(spec, raw)

def _match_existing(spec, B, A, nB, j0, cnT):
    S = np.linalg.inv(B['T']) @ cnT; a0 = aSide(nB, j0)
    wx = S[0, 0]*np.cos(a0)+S[0, 1]*np.sin(a0); wy = S[1, 0]*np.cos(a0)+S[1, 1]*np.sin(a0)
    j = int(np.floor((np.pi/2-np.arctan2(wy, wx))*B['n']/TAU+.5)) % B['n']
    assert abs(np.cos(aSide(B['n'], j))-wx)+abs(np.sin(aSide(B['n'], j))-wy) < 1e-5, 'side map'
    assert spec['pat'][B['n']][j] == A['n'], 'pattern clash'
    return j, S[0, 0]*S[1, 1]-S[0, 1]*S[1, 0] < 0

def tiling_patch(spec, LIM=130):
    R = []
    def mk(n, T):
        r = dict(id=len(R), n=n, T=T, c=T @ np.array([0, 0, 1.]), nb=[None]*n); R.append(r); return r
    mk(spec['n0'], np.eye(3))
    i = 0
    while i < len(R):
        A = R[i]; i += 1
        for k in range(A['n']):
            if A['nb'][k]: continue
            nB, j0, cn = _place_across(spec, A, k)
            if cn is None: continue
            cT, seam = cn; c = cT @ np.array([0, 0, 1.])
            B = next((r for r in R if np.linalg.norm(r['c']-c) < 1e-6), None); j, flip = j0, False
            if B is None:
                if len(R) >= LIM: continue
                B = mk(nB, cT)
            else:
                assert B['n'] == nB, 'type clash'
                j, flip = _match_existing(spec, B, A, nB, j0, cT)
                assert not B['nb'][j] or (B['nb'][j]['r'] is A and B['nb'][j]['s'] == k), 'patch inconsistent'
            A['nb'][k] = dict(r=B, s=j, flip=flip, seam=seam); B['nb'][j] = dict(r=A, s=k, flip=flip, seam=seam)
    return R

def chain_walk(r, c, d0=1):
    """the rooms around one corner. A step leaves through side c+1 (dir +1) or side c (dir -1); a mirrored gluing reverses dir"""
    lst = []; cr, cc, d = r, c, d0
    for _ in range(90):
        k = (cc+1) % cr['n'] if d > 0 else cc
        lst.append((cr, cc, d, k))
        x = cr['nb'][k]
        if not x: return False, lst
        d = -d if x['flip'] else d; cr = x['r']; cc = x['s'] if d > 0 else (x['s']-1+x['r']['n']) % x['r']['n']
        if cr is r and cc == c and d == d0: return True, lst
    raise RuntimeError('corner chain too long')

CAT = dict(flat=0, hyper=1, sphere=2, grid=3)

def all_specs():
    items = [(_make(d, '.'.join(map(str, d['vc']))), g) for g in ('flat', 'hyper', 'sphere') for d in SPECDEFS[g]]
    combos = [('plain', 'none'), ('flip', 'none'), ('none', 'plain'), ('none', 'flip'), ('plain', 'plain'), ('flip', 'plain'), ('plain', 'flip')]
    for W in (5, 6, 7):
        for H in (4, 5):
            for wx, wy in combos: items.append((grid_spec(W, H, wx, wy), 'grid'))
    return items

def build_specs():
    D = []
    for sp, cat in all_specs():
        P = tiling_patch(sp); finite = all(all(r['nb']) for r in P)
        hubok, hubl = chain_walk(P[0], 0); hub = {x[0]['id'] for x in hubl} if hubok and not sp['sub'] else set()
        seen, cyc = set(), []
        for r in P:
            for c in range(r['n']):
                ok, lst = chain_walk(r, c)
                if not ok: continue
                key = ','.join(map(str, sorted(x[0]['id'] for x in lst)))
                if key in seen: continue
                seen.add(key); cyc.append(([x[0]['id'] for x in lst], [x[3] for x in lst]))
        D.append(dict(cat=cat, name=sp['name'], vcn=len(sp['vc']), hol=abs(holonomy(sp['vc'])), sub=sp['sub'], wrapped=sp['group'] is not None, finite=finite,
                      whole=(not sp['sub'] and finite and len(P) <= 34), n=[r['n'] for r in P],
                      nb=[[(x['r']['id'], x['s'], int(x['flip']), int(x['seam'])) if x else None for x in r['nb']] for r in P],
                      hub=[int(r['id'] in hub) for r in P], cyc=cyc))
    NS = len(D); RP = max(len(d['n']) for d in D); S = 12; L = 8; C = max(len(d['cyc']) for d in D)
    assert max(len(c[0]) for d in D for c in d['cyc']) <= L
    T = dict(n=np.zeros((NS, RP), np.int32), nbr=-np.ones((NS, RP, S), np.int32), nbs=np.zeros((NS, RP, S), np.int32), flip=np.zeros((NS, RP, S), np.int32),
             seam=np.zeros((NS, RP, S), np.int32), hub=np.zeros((NS, RP), np.int32), nrooms=np.zeros(NS, np.int32),
             cyc_room=np.zeros((NS, C, L), np.int32), cyc_k=np.zeros((NS, C, L), np.int32), cyc_len=np.zeros((NS, C), np.int32),
             whole=np.zeros(NS, np.int32), sub=np.zeros(NS, np.int32), wrapped=np.zeros(NS, np.int32), vcn=np.zeros(NS, np.int32), hol=np.zeros(NS, np.float32),
             cat=np.zeros(NS, np.int32))
    for i, d in enumerate(D):
        m = len(d['n']); T['nrooms'][i] = m; T['n'][i, :m] = d['n']; T['hub'][i, :m] = d['hub']
        for r, row in enumerate(d['nb']):
            for k, x in enumerate(row):
                if x: T['nbr'][i, r, k], T['nbs'][i, r, k], T['flip'][i, r, k], T['seam'][i, r, k] = x
        for c, (rooms, ks) in enumerate(d['cyc']):
            l = len(rooms); T['cyc_len'][i, c] = l; T['cyc_room'][i, c, :l] = rooms; T['cyc_k'][i, c, :l] = ks
        for k in ('whole', 'sub', 'wrapped', 'vcn', 'hol'): T[k][i] = d[k]
        T['cat'][i] = CAT[d['cat']]
    meta = [{k: d[k] for k in ('cat', 'name', 'vcn', 'hol', 'sub', 'wrapped', 'finite', 'whole')} for d in D]
    return T, meta

def load_specs(rebuild=False):
    """constant tables as jax arrays; built once (about a minute) and cached next to this file"""
    import jax.numpy as jnp
    path = os.path.join(_D, 'specs.npz')
    if rebuild or not os.path.exists(path):
        T, meta = build_specs(); os.makedirs(_D, exist_ok=True)
        np.savez_compressed(path, **T); json.dump(meta, open(os.path.join(_D, 'specs.json'), 'w'))
    z = np.load(path)
    return {k: jnp.asarray(z[k]) for k in z.files}

if __name__ == '__main__':
    import time; t = time.time(); load_specs(rebuild=True); print('specs built in %.1fs' % (time.time()-t))
