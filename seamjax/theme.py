"""
How the game looks and sounds: every presentation choice in one place. Gameplay never reads this file (core/kinds.py
says what things ARE; this says how they are SHOWN), so changing it never changes the simulation or a trained agent's
vector observations. The pixel renderer (rl/render.py) does use its colours.

Sounds and looks can be procedural or come from files:

    Sound(synth='shoot')                     generated by JAX (app/audio.py: ONE_SHOTS / LOOPS); 3 random variants
    Sound(file='sounds/zap.wav')             a sound file (wav / ogg); a tuple of files = variants picked at random
    Look((1., .5, .2), 'pentagon')           a procedural shape: disk, ring, pentagon, heart, streak
    Look((1., 1., 1.), texture='textures/bat.png')    an image, tinted by the colour (white = as drawn)
    WorldLook(floor='rings') / WorldLook(texture='textures/stone.png', texture_scale=128.)

File paths are relative to seamjax/assets/ (or absolute). Colours are (r, g, b) in 0..1.

To re-skin: edit THEME below, or set seamjax.theme.THEME = THEME.replace(...) before the viewer starts.
"""
import os
from dataclasses import dataclass, field, replace

ASSETS = os.path.join(os.path.dirname(__file__), 'assets')
SHAPES = ('disk', 'ring', 'pentagon', 'heart', 'streak')     # the procedural sprite shapes (app/gl/shaders.py SPRITE_FS)
FLOORS = ('grid', 'rings', 'dots', 'diagonals')              # the procedural floor patterns (app/gl/shaders.py SCENE_FS)


def asset(path):
    return path if os.path.isabs(path) else os.path.join(ASSETS, path)


@dataclass(frozen=True)
class Sound:
    synth: str = None           # a generator in app/audio.py
    file: object = None         # a path, or a tuple of paths (variants)
    volume: float = 1.
    pan: bool = True            # placed left / right by where it happens on screen


@dataclass(frozen=True)
class Burst:
    """particles thrown out from where something happened"""
    count: int
    colour: tuple
    speed: float                # px/s at the start
    life: float                 # seconds
    size: float
    spread: float = 1.


@dataclass(frozen=True)
class Effect:
    """what an event does to the screen and the speakers"""
    sound: Sound = None
    bursts: tuple = ()
    shake: float = 0.           # screen shake (decays)
    hit: float = 0.             # red hit flash with colour fringing
    flash: float = 0.           # white flash
    fade: float = 0.            # fade to black and back (a new floor)


@dataclass(frozen=True)
class Look:
    """how one thing is drawn: a procedural shape or a texture, with additive glow"""
    colour: tuple
    shape: str = 'disk'         # SHAPES; ignored when there is a texture
    texture: str = None
    glow: float = 1.            # brightness
    size: float = None          # radius; None = the thing's own radius (gameplay)
    extent: float = None        # half-size of the glow quad; None = from the radius
    width: float = 0.           # ring: line width; streak: length
    spin: float = 0.            # turns per second (pentagon, texture)
    pulse: float = 0.           # size wobble (share of the radius)


@dataclass(frozen=True)
class EnemyLook:
    look: Look
    kill: Effect


@dataclass(frozen=True)
class WorldLook:
    floor: str = 'grid'         # FLOORS; ignored when there is a texture
    texture: str = None         # tiled over the floor in room coordinates
    texture_scale: float = 128. # px per texture repeat
    drone: Sound = None         # background loop


@dataclass(frozen=True)
class Walls:
    """colours of the room's structure. wall and obstacle are (saturation, lightness) of the room's own hue"""
    wall: tuple = (.55, .58)
    obstacle: tuple = (.35, .26)
    door: tuple = (.59, .92, 1.)
    door_other_side: tuple = (1., .745, .43)          # a door on the second side of an inner wall
    hunter_door: tuple = (1., .24, .35)              # where the Hunter will come through (pulses)
    roamer_door: tuple = (1., .6, .2)                # where a follower will come through (pulses)
    gated_wall: tuple = (.35, .59, 1.)
    solid_wall: tuple = (1., .39, .62)


@dataclass(frozen=True)
class Theme:
    events: dict                # event name (app/events.py) -> Effect; 'kill' comes from the enemy's look
    looks: dict                 # thing -> Look
    enemies: dict               # enemy kind name (core/kinds.py) -> EnemyLook
    worlds: dict                # world kind (flat / hyper / sphere / grid) -> WorldLook
    walls: Walls = field(default_factory=Walls)
    heartbeat: Sound = None     # loop whose volume follows the Hunter's distance
    flash_colour: tuple = (1., 1., 1.)    # an enemy or the Hunter just hit
    players: dict = field(default_factory=dict)    # player class name (core/kinds.py) -> Look; default looks['player']
    weapons: dict = field(default_factory=dict)    # weapon name -> Look of its bullets (or its swing); default looks['player_bullet']

    def replace(self, **kw): return replace(self, **kw)

    def player(self, cls_name):
        return self.players.get(cls_name, self.looks['player'])

    def weapon(self, name):
        return self.weapons.get(name, self.looks['player_bullet'])

    def enemy(self, name):
        """the look of an enemy kind; a kind without one gets a plain grey disk"""
        return self.enemies.get(name, DEFAULT_ENEMY)

    def effect(self, event):
        """the Effect of an event dict from app/events.py"""
        if event['name'] == 'kill':
            from seamjax.core import kinds
            return self.enemy(kinds.ENEMY_KINDS[event['kind']].name).kill
        return self.events.get(event['name'], NOTHING)

    def textures(self):
        """every texture file the theme uses (sprites first, then floors)"""
        looks = list(self.looks.values()) + [e.look for e in self.enemies.values()] + list(self.players.values()) + list(self.weapons.values())
        return sorted({l.texture for l in looks if l.texture}), sorted({w.texture for w in self.worlds.values() if w.texture})

    def sounds(self):
        """every Sound the theme uses: (one-shots, loops)"""
        shots = {e.sound for e in self.events.values() if e.sound} | {e.kill.sound for e in self.enemies.values() if e.kill.sound}
        loops = {w.drone for w in self.worlds.values() if w.drone} | ({self.heartbeat} if self.heartbeat else set())
        return shots, loops


NOTHING = Effect()
RED = (1., .36, .45)
GOLD = (1., .89, .48)
LILAC = (.85, .75, 1.)

def _kill(colour, synth):
    return Effect(sound=Sound(synth=synth), bursts=(Burst(26, colour, 250, .65, 6), Burst(8, (1., 1., 1.), 160, .35, 4)), shake=.28)

DEFAULT_ENEMY = EnemyLook(Look((.7, .7, .7)), _kill((.7, .7, .7), 'kill_charger'))

THEME = Theme(
    events=dict(
        shoot=Effect(Sound(synth='shoot', volume=.6), (Burst(4, GOLD, 130, .22, 3, spread=.6),)),
        swing=Effect(Sound(synth='swing', volume=.7), (Burst(6, LILAC, 160, .18, 3, spread=.8),)),
        hit=Effect(Sound(synth='hit', pan=False), (Burst(18, (1., .35, .4), 190, .55, 6),), shake=.9, hit=1.),
        heal=Effect(Sound(synth='heal'), (Burst(14, (1., .45, .6), 120, .7, 5),)),
        death=Effect(Sound(synth='death', pan=False), (Burst(70, (1., .7, .75), 330, 1.1, 8),), shake=1.4),
        hunter_hit=Effect(Sound(synth='hunter_hit'), (Burst(8, RED, 170, .4, 4),)),
        hunter_die=Effect(Sound(synth='hunter_die'), (Burst(60, RED, 300, 1., 7),), shake=.8, flash=.6),
        open=Effect(Sound(synth='open', pan=False)),
        descend=Effect(Sound(synth='descend', pan=False), fade=1.),
        newrun=Effect(fade=1.),
    ),
    looks=dict(
        player=Look((.8, .9, 1.), glow=.85, extent=44),
        aim=Look(GOLD, 'streak', glow=1.2, size=1.6, extent=40, width=20),
        player_bullet=Look(GOLD, 'streak', glow=1.5, size=3, extent=40, width=16),
        enemy_bullet=Look((1., .54, .82), 'streak', glow=1.4, size=4.5, extent=36, width=10),
        pickup=Look(RED, 'heart', glow=1.1, size=11, extent=40, pulse=.08),
        hunter=Look(RED, 'pentagon', glow=1.1, spin=.8),
        telegraph=Look((1., 1., 1.), 'ring', glow=.8, width=1.6),          # an enemy about to appear
        pad=Look((.55, 1., .84), 'ring', size=18, extent=34, width=3),     # the exit pad (pulses; grey until the room is clear)
        pad_closed=Look((.5, .5, .5), 'ring', glow=.6, size=18, extent=34, width=3),
        pad_glow=Look((.55, 1., .84), glow=.35, size=8, extent=40),
    ),
    enemies=dict(
        chaser=EnemyLook(Look((1., .48, .27)), _kill((1., .48, .27), 'kill_charger')),
        shooter=EnemyLook(Look((.71, .49, 1.)), _kill((.71, .49, 1.), 'kill_shooter')),
        stalker=EnemyLook(Look((.35, .95, .75)), _kill((.35, .95, .75), 'kill_charger')),
        flanker=EnemyLook(Look((1., .8, .3), 'pentagon', size=12.), _kill((1., .8, .3), 'kill_shooter')),
    ),
    worlds=dict(
        flat=WorldLook('grid', drone=Sound(synth='drone_flat')),
        hyper=WorldLook('rings', drone=Sound(synth='drone_hyper')),
        sphere=WorldLook('dots', drone=Sound(synth='drone_sphere')),
        grid=WorldLook('diagonals', drone=Sound(synth='drone_grid')),
    ),
    heartbeat=Sound(synth='heartbeat'),
    players=dict(                                      # gunner: looks['player']
        scatter=Look((1., .85, .55), glow=.85, extent=44),
        lancer=Look((.6, 1., .95), glow=.85, extent=44),
        blade=Look(LILAC, glow=.85, extent=44),
    ),
    weapons=dict(                                      # blaster: looks['player_bullet']
        scatter=Look(GOLD, 'streak', glow=1.3, size=2.5, extent=30, width=9),
        lance=Look((.6, 1., .95), 'streak', glow=1.8, size=3, extent=48, width=28),
        blade=Look(LILAC, 'streak', glow=.55, size=2.),            # the swing: short streaks along the edge of the arc
    ),
)
