"""
Tilings, built on the device.

Every world is a tiling of a constant-curvature surface (sphere / plane / hyperbolic plane) by regular polygons,
generated by placing polygons with 3x3 isometry matrices and identifying rooms that land on the same spot.
Wrapped worlds are the flat plane quotiented by a group of isometries (translations, glide reflections).

This file holds (1) the CATALOGUE of worlds, which is plain data: a vertex recipe like [4, 6, 12] plus the rule for which
polygon sits across each side, and (2) a JAX builder that grows each patch, closes the corner loops and flattens everything
into the constant tables the generator (seamjax/gen) samples from. The builder is one jitted program (float64 inside, since hyperbolic
poses get large); on first use it takes seconds and the result is cached next to this file.

Poses are 3x3 matrices acting on points (x, y, 1) of the model surface with curvature kappa = +1 / 0 / -1.
"""
import os, json, numpy as np, jax, jax.numpy as jnp
from jax import lax

TAU = 2*np.pi
_D = os.path.join(os.path.dirname(__file__), 'data')
LIM, S, L, CMAX, NPOLY = 130, 12, 8, 256, 13        # patch size cap, sides, corner-loop length cap, cycle cap, polygon sizes 0..12

# ---------------------------------------------------------------- the catalogue (data)
def reg(p, q): return dict(vc=[p]*q, pat={p: [p]*p})
def bip(a, b, k): return dict(vc=[b if i % 2 else a for i in range(k)], pat={a: [b]*a, b: [a]*b})
def abb(a, b): return dict(vc=[a, b, b], pat={a: [b]*a, b: [b if i % 2 else a for i in range(b)]})
def abc(a, b, c): return dict(vc=[a, b, c], pat={a: [c if i % 2 else b for i in range(a)], b: [c if i % 2 else a for i in range(b)], c: [b if i % 2 else a for i in range(c)]})
def rhomb(): return dict(vc=[3, 4, 6, 4], pat={3: [4, 4, 4], 4: [3, 6, 3, 6], 6: [4]*6})
SPECDEFS = dict(
    flat=[reg(4, 4), reg(4, 4), reg(4, 4), reg(3, 6), reg(6, 3), abb(4, 8), abb(3, 12), abc(4, 6, 12), rhomb(), bip(3, 6, 4)],
    hyper=[reg(4, 5), reg(4, 6), reg(4, 7), reg(3, 7), reg(3, 8), reg(5, 4), reg(5, 5), reg(6, 4), reg(7, 3), reg(8, 3),
           abc(4, 8, 10), abc(4, 10, 12), abc(6, 8, 10), abb(4, 12), abb(5, 10), bip(3, 7, 4), bip(4, 5, 4), bip(4, 6, 4), bip(3, 8, 4)],
    sphere=[reg(3, 5), reg(5, 3), abb(4, 6), abb(3, 8), abc(4, 6, 8), abb(5, 6), abb(3, 10), bip(3, 4, 4), bip(3, 5, 4)])
CAT = dict(flat=0, hyper=1, sphere=2, grid=3)
WRAP = dict(none=0, plain=1, flip=2)

def all_specs():
    """[(vertex recipe, side pattern, category, name, grid or None)]; grid = (W, H, wrap_x, wrap_y) for wrapped worlds"""
    out = [(d['vc'], d['pat'], g, '.'.join(map(str, d['vc'])), None) for g in ('flat', 'hyper', 'sphere') for d in SPECDEFS[g]]
    combos = [('plain', 'none'), ('flip', 'none'), ('none', 'plain'), ('none', 'flip'), ('plain', 'plain'), ('flip', 'plain'), ('plain', 'flip')]
    for W in (5, 6, 7):
        for H in (4, 5):
            for wx, wy in combos:
                d = reg(4, 4); out.append((d['vc'], d['pat'], 'grid', f'grid:{W}x{H}:{wx}:{wy}', (W, H, wx, wy)))
    return out

def encode():
    """the catalogue as stacked numeric arrays, one row per world"""
    sp = all_specs(); N = len(sp)
    E = dict(vc=np.zeros((N, 8)), n0=np.zeros(N, np.int32), pat=np.zeros((N, NPOLY, S), np.int32), grid=np.zeros(N, np.int32),
             W=np.zeros(N), H=np.zeros(N), wx=np.zeros(N, np.int32), wy=np.zeros(N, np.int32), cat=np.zeros(N, np.int32))
    for i, (vc, pat, cat, name, grid) in enumerate(sp):
        E['vc'][i, :len(vc)] = vc; E['n0'][i] = vc[0]; E['cat'][i] = CAT[cat]
        for n, row in pat.items(): E['pat'][i, n, :n] = row
        if grid: E['grid'][i] = 1; E['W'][i], E['H'][i] = grid[0], grid[1]; E['wx'][i], E['wy'][i] = WRAP[grid[2]], WRAP[grid[3]]
    return E, [dict(name=x[3], cat=x[2], vcn=len(x[0]), sub=x[4] is not None, hol=abs(sum(180-360/n for n in x[0])-360)) for x in sp]

# ---------------------------------------------------------------- the builder (JAX, float64)
def _aside(n, k): return jnp.pi/2 - TAU*k/n          # math angle of side k of an n-gon (side 0 up, clockwise)
def _rot(t): c, s = jnp.cos(t), jnp.sin(t); return jnp.array([[c, -s, 0.], [s, c, 0.], [0., 0., 1.]])
def _trans(k, d):
    ck = jnp.where(k > 0, jnp.cos(d), jnp.where(k < 0, jnp.cosh(d), 1.)); sk = jnp.where(k > 0, jnp.sin(d), jnp.where(k < 0, jnp.sinh(d), d))
    return jnp.array([[ck, 0., sk], [0., 1., 0.], [-k*sk, 0., ck]])

def _geometry(vc):
    """curvature sign and the in-radius of every polygon size, for a vertex recipe (zero-padded, up to 8 entries)"""
    m = vc > 0; nn = jnp.where(m, vc, 4.)
    F = jnp.sum(jnp.where(m, .5-1/nn, 0.)); kappa = jnp.where(jnp.abs(F-1) < 1e-9, 0., jnp.where(F > 1, -1., 1.))
    ang = lambda n, s: jnp.where(kappa < 0, 2*jnp.arcsin(jnp.cos(jnp.pi/n)/jnp.cosh(s/2)), 2*jnp.arcsin(jnp.minimum(1., jnp.cos(jnp.pi/n)/jnp.cos(s/2))))
    hi0 = jnp.where(kappa < 0, 30., 2*jnp.min(jnp.where(m, jnp.pi/nn, 1e9))*(1-1e-9))
    def bis(_, lh):                                  # side length such that the corner angles add up to a full turn
        lo, hi = lh; mid = (lo+hi)/2; f = jnp.sum(jnp.where(m, ang(nn, mid), 0.))-TAU
        up = jnp.where(kappa < 0, f > 0, f < 0); return jnp.where(up, mid, lo), jnp.where(up, hi, mid)
    lo, hi = lax.fori_loop(0, 200, bis, (jnp.float64(1e-6), hi0)); s = jnp.where(kappa == 0, 1., (lo+hi)/2)
    ns = jnp.maximum(jnp.arange(NPOLY), 3).astype(jnp.float64); a = ang(ns, s); ca = jnp.cos(a/2)/jnp.sin(jnp.pi/ns)
    rho = jnp.where(kappa < 0, jnp.arccosh(jnp.maximum(ca, 1.)), jnp.where(kappa > 0, jnp.arccos(jnp.clip(ca, -1., 1.)), s/(2*jnp.tan(jnp.pi/ns))))
    return kappa, rho

def _build_one(e):
    kappa, rho = _geometry(e['vc']); pat = e['pat']; sub = e['grid'] > 0; W, H = e['W'], e['H']
    one, zero = jnp.float64(1.), jnp.float64(0.)
    g1 = jnp.where(e['wx'] == 2, jnp.array([[1, 0, W], [0, -1, H-1], [0, 0, 1.]]), jnp.array([[1, 0, W], [0, 1, 0], [0, 0, 1.]]))
    g2 = jnp.where(e['wy'] == 2, jnp.array([[-1, 0, W-1], [0, 1, H], [0, 0, 1.]]), jnp.array([[1, 0, 0], [0, 1, H], [0, 0, 1.]]))
    gens = [g1, g2]; invs = [jnp.linalg.inv(g1), jnp.linalg.inv(g2)]; has = [e['wx'] > 0, e['wy'] > 0]; o3 = jnp.array([0., 0., 1.])

    def canon(M):
        """back into the fundamental domain; ok=False if it falls off a non-wrapping edge; seam=True if a seam was crossed"""
        def it(_, c):
            M, seam = c
            for a in range(2):
                ctr = M @ o3; hi = (H if a else W)-.5; lo_ = has[a] & (ctr[a] < -.5); hi_ = has[a] & (ctr[a] > hi)
                M = jnp.where(lo_, gens[a] @ M, jnp.where(hi_, invs[a] @ M, M)); seam = seam | lo_ | hi_
            return M, seam
        Mg, seam = lax.fori_loop(0, 60, it, (M, jnp.bool_(False))); c = Mg @ o3
        ok = ~((c[0] < -.5) | (c[0] > W-.5) | (c[1] < -.5) | (c[1] > H-.5))
        return jnp.where(sub, Mg, M), jnp.where(sub, seam, False), jnp.where(sub, ok, True)

    st = dict(T=jnp.zeros((LIM, 3, 3)).at[0].set(jnp.eye(3)), n=jnp.zeros(LIM, jnp.int32).at[0].set(e['n0']), c=jnp.zeros((LIM, 3)).at[0].set(o3),
              nbr=-jnp.ones((LIM, S), jnp.int32), nbs=jnp.zeros((LIM, S), jnp.int32), flip=jnp.zeros((LIM, S), jnp.int32), seam=jnp.zeros((LIM, S), jnp.int32),
              count=jnp.int32(1))

    def side_step(i, k, st):
        An = st['n'][i]; active = (i < st['count']) & (k < An) & (st['nbr'][i, k] < 0)
        nB = pat[An, jnp.minimum(k, S-1)]; j0 = jnp.argmax(pat[nB] == An)
        raw = st['T'][i] @ _rot(_aside(An, k)) @ _trans(kappa, rho[An]+rho[nB]) @ _rot(jnp.pi-_aside(nB, j0))
        cT, seam, ok = canon(raw); c = cT @ o3
        d = jnp.where(jnp.arange(LIM) < st['count'], jnp.linalg.norm(st['c']-c, axis=1), 1e9); b0 = jnp.argmin(d); found = d[b0] < 1e-6
        isnew = ~found & (st['count'] < LIM); go = active & ok & (found | isnew)
        B = jnp.where(found, b0, st['count'])
        # which side of the existing room B faces us, and is the gluing mirrored?
        Sm = jnp.linalg.inv(st['T'][b0]) @ cT; a0 = _aside(nB, j0); Bn = st['n'][b0]
        wx = Sm[0, 0]*jnp.cos(a0)+Sm[0, 1]*jnp.sin(a0); wy = Sm[1, 0]*jnp.cos(a0)+Sm[1, 1]*jnp.sin(a0)
        jf = jnp.mod(jnp.floor((jnp.pi/2-jnp.arctan2(wy, wx))*Bn/TAU+.5).astype(jnp.int32), jnp.maximum(Bn, 1))
        flipf = (Sm[0, 0]*Sm[1, 1]-Sm[0, 1]*Sm[1, 0]) < 0
        j = jnp.where(found, jf, j0); flip = jnp.where(found, flipf, False)
        w = lambda a, idx, v: jnp.where(go, a.at[idx].set(v), a)
        st = {**st, 'T': w(st['T'], B, jnp.where(found, st['T'][B], cT)), 'n': w(st['n'], B, jnp.where(found, st['n'][B], nB)),
              'c': w(st['c'], B, jnp.where(found, st['c'][B], c)), 'count': st['count']+(go & ~found)}
        st = {**st, 'nbr': w(w(st['nbr'], (i, k), B), (B, j), i), 'nbs': w(w(st['nbs'], (i, k), j), (B, j), k),
              'flip': w(w(st['flip'], (i, k), flip.astype(jnp.int32)), (B, j), flip.astype(jnp.int32)),
              'seam': w(w(st['seam'], (i, k), seam.astype(jnp.int32)), (B, j), seam.astype(jnp.int32))}
        return st

    st = lax.fori_loop(0, LIM, lambda i, st: lax.fori_loop(0, S, lambda k, st: side_step(i, k, st), st), st)
    n, nbr, nbs, flipt, count = st['n'], st['nbr'], st['nbs'], st['flip'], st['count']
    finite = jnp.all(jnp.where((jnp.arange(LIM) < count)[:, None] & (jnp.arange(S)[None] < n[:, None]), nbr >= 0, True))

    def chain(r, c):
        """the rooms around one corner (see the numpy reference): leave through side c+1 (dir +1) or side c (dir -1); a mirrored gluing reverses dir"""
        def stp(t, cs):
            cr, cc, d, alive, closed, ln, rooms, ks = cs; run = alive & ~closed
            k = jnp.where(d > 0, jnp.mod(cc+1, n[cr]), cc); x = nbr[cr, k]; miss = x < 0
            rooms = jnp.where(run, rooms.at[t].set(cr), rooms); ks = jnp.where(run, ks.at[t].set(k), ks); ln = jnp.where(run, t+1, ln)
            d2 = jnp.where(flipt[cr, k] == 1, -d, d); xr = jnp.maximum(x, 0)
            cc2 = jnp.where(d2 > 0, nbs[cr, k], jnp.mod(nbs[cr, k]-1+n[xr], n[xr]))
            cl = (xr == r) & (cc2 == c) & (d2 == 1)
            return (jnp.where(run & ~miss, xr, cr), jnp.where(run & ~miss, cc2, cc), jnp.where(run & ~miss, d2, d), alive & ~(run & miss), closed | (run & ~miss & cl), ln, rooms, ks)
        cr, cc, d, alive, closed, ln, rooms, ks = lax.fori_loop(0, 2*L, stp, (r, c, jnp.int32(1), jnp.bool_(True), jnp.bool_(False), jnp.int32(0), jnp.zeros(2*L, jnp.int32), jnp.zeros(2*L, jnp.int32)))
        return closed, ln, rooms[:L], ks[:L]
    rr, cc_ = jnp.meshgrid(jnp.arange(LIM), jnp.arange(S), indexing='ij')
    ok, ln, rooms, ks = jax.vmap(chain)(rr.reshape(-1), cc_.reshape(-1))
    valid = (cc_.reshape(-1) < n[rr.reshape(-1)]) & (rr.reshape(-1) < count)
    overflow = jnp.any(ok & valid & (ln > L))                                                          # a loop longer than the table allows
    ok = ok & valid & (ln <= L)
    srt = jnp.sort(jnp.where(jnp.arange(L)[None] < ln[:, None], rooms, 9999), axis=1)                 # a corner loop is identified by its set of rooms
    eq = jnp.all(srt[:, None, :] == srt[None, :, :], axis=2) & ok[:, None] & ok[None, :]
    keep = ok & ~jnp.any(jnp.tril(eq, -1), axis=1)                                                    # first occurrence only, in (room, corner) order
    slot = jnp.cumsum(keep)-1; tgt = jnp.where(keep, slot, CMAX)
    cyc_room = jnp.zeros((CMAX+1, L), jnp.int32).at[tgt].set(jnp.where(jnp.arange(L)[None] < ln[:, None], rooms, 0).astype(jnp.int32))[:CMAX]
    cyc_k = jnp.zeros((CMAX+1, L), jnp.int32).at[tgt].set(jnp.where(jnp.arange(L)[None] < ln[:, None], ks, 0).astype(jnp.int32))[:CMAX]
    cyc_len = jnp.zeros(CMAX+1, jnp.int32).at[tgt].set(ln.astype(jnp.int32))[:CMAX]
    hok, hln, hrooms, _ = chain(jnp.int32(0), jnp.int32(0))
    hub = jnp.zeros(LIM, jnp.int32).at[jnp.where(jnp.arange(L) < hln, hrooms, LIM)].set(1, mode='drop') * (hok & ~sub)
    vc = e['vc']; hol = jnp.abs(jnp.sum(jnp.where(vc > 0, 180-360/jnp.where(vc > 0, vc, 1.), 0.))-360)
    return dict(cvec=st['c'], n=n, nbr=nbr, nbs=nbs, flip=flipt, seam=st['seam'], hub=hub.astype(jnp.int32), nrooms=count, cyc_room=cyc_room, cyc_k=cyc_k, cyc_len=cyc_len,
                whole=(~sub & finite & (count <= 34)).astype(jnp.int32), sub=sub.astype(jnp.int32), wrapped=sub.astype(jnp.int32),
                vcn=jnp.sum(vc > 0).astype(jnp.int32), hol=hol, cat=e['cat'], n_cycles=jnp.sum(keep).astype(jnp.int32), overflow=overflow)

def build_specs(device=None):
    """grow every tiling patch and close every corner loop, on the device (or on `device`). Returns (tables, metadata)."""
    from seamjax.backend import table_device
    E, meta = encode()
    with jax.default_device(device or table_device()), jax.enable_x64(True):               # float64: on the CPU if the device (Metal) has none
        out = jax.jit(lambda E: lax.map(_build_one, E))({k: jnp.asarray(v) for k, v in E.items()})
        out = {k: np.asarray(v) for k, v in out.items()}
    assert not out['overflow'].any(), 'a corner loop is longer than L'
    RP = int(out['nrooms'].max()); C = int(out['n_cycles'].max()); assert C <= CMAX
    T = dict(cvec=out['cvec'][:, :RP].astype(np.float32), n=out['n'][:, :RP].astype(np.int32), nbr=out['nbr'][:, :RP], nbs=out['nbs'][:, :RP], flip=out['flip'][:, :RP], seam=out['seam'][:, :RP],
             hub=out['hub'][:, :RP], nrooms=out['nrooms'].astype(np.int32), cyc_room=out['cyc_room'][:, :C], cyc_k=out['cyc_k'][:, :C], cyc_len=out['cyc_len'][:, :C],
             whole=out['whole'], sub=out['sub'], wrapped=out['wrapped'], vcn=out['vcn'], hol=out['hol'].astype(np.float32), cat=out['cat'])
    return T, meta

def load_specs(rebuild=False):
    """constant tables as jax arrays; built once on the device and cached next to this file"""
    from seamjax.backend import ensure; ensure()                       # start the backend now so a problem shows up here, with advice
    path = os.path.join(_D, 'specs.npz')
    if rebuild or not os.path.exists(path) or 'cvec' not in np.load(path).files:
        T, meta = build_specs(); os.makedirs(_D, exist_ok=True)
        np.savez_compressed(path, **T); json.dump(meta, open(os.path.join(_D, 'specs.json'), 'w'))
    z = np.load(path)
    return {k: jnp.asarray(z[k]) for k in z.files}

if __name__ == '__main__':
    import time; t = time.time(); load_specs(rebuild=True); print('specs built in %.1fs' % (time.time()-t))
